# Seals the HebrewBooks bucket settings for a release (see HebrewBooksMirrorKey.cs).
# Input: the mirror JSON (publicMirrorUrlFormat + r2* fields), from -Json or $env:HB_MIRROR_JSON.
# Output, both beside the catalog and both outside git:
#   hb-mirror.json            - publicMirrorUrlFormat in clear, every r2* field AES-GCM sealed as r2Sealed
#   HebrewBooksMirrorKey.g.cs - a fresh random key for this build, split into two XOR halves
# Run: pwsh Build/seal-hb-mirror.ps1            (reads $env:HB_MIRROR_JSON)
#      pwsh Build/seal-hb-mirror.ps1 -Json (Get-Content plain.json -Raw)
param([string]$Json = $env:HB_MIRROR_JSON, [string]$OutDir)
$ErrorActionPreference = 'Stop'
if (-not $Json) { throw 'No mirror JSON: set HB_MIRROR_JSON or pass -Json' }

$dir = if ($OutDir) { $OutDir } else { Join-Path $PSScriptRoot '..\KitveiHakodesh\CSharpBackend\KitveiHakodesh.Core\HebrewBooks' }
$settings = $Json | ConvertFrom-Json

$bucket = [ordered]@{}
foreach ($p in $settings.PSObject.Properties) { if ($p.Name -like 'r2*') { $bucket[$p.Name] = $p.Value } }

$out = [ordered]@{ publicMirrorUrlFormat = $settings.publicMirrorUrlFormat }
$key = [byte[]]::new(32); [Security.Cryptography.RandomNumberGenerator]::Fill($key)
if ($bucket.Count -gt 0) {
    $plain = [Text.Encoding]::UTF8.GetBytes(($bucket | ConvertTo-Json -Compress))
    $nonce = [byte[]]::new(12); [Security.Cryptography.RandomNumberGenerator]::Fill($nonce)
    $cipher = [byte[]]::new($plain.Length); $tag = [byte[]]::new(16)
    $aes = [Security.Cryptography.AesGcm]::new($key, 16)
    $aes.Encrypt($nonce, $plain, $cipher, $tag); $aes.Dispose()
    $out.r2Sealed = [Convert]::ToBase64String($nonce + $cipher + $tag)
}
[IO.File]::WriteAllText((Join-Path $dir 'hb-mirror.json'), ($out | ConvertTo-Json -Compress), [Text.UTF8Encoding]::new($false))

$left = [byte[]]::new(32); [Security.Cryptography.RandomNumberGenerator]::Fill($left)
$right = [byte[]]::new(32); for ($i = 0; $i -lt 32; $i++) { $right[$i] = $key[$i] -bxor $left[$i] }
$hex = { param($b) ($b | ForEach-Object { '0x{0:x2}' -f $_ }) -join ', ' }
$cs = @"
// <auto-generated> by Build/seal-hb-mirror.ps1 - never commit. </auto-generated>
namespace KitveiHakodesh.Core.HebrewBooks
{
    internal static partial class HebrewBooksMirrorKey
    {
        static partial void Fill(ref byte[]? left, ref byte[]? right)
        {
            left = new byte[] { $(& $hex $left) };
            right = new byte[] { $(& $hex $right) };
        }
    }
}
"@
[IO.File]::WriteAllText((Join-Path $dir 'HebrewBooksMirrorKey.g.cs'), $cs, [Text.UTF8Encoding]::new($false))
Write-Host "hb-mirror sealed: public mirror $([bool]$out.publicMirrorUrlFormat), bucket fields $($bucket.Count)"
