# Builds Resources\KleiKodeshMacros.dotm: a Word template holding one VBA macro per
# add-in command, so users can put any command on the Quick Access Toolbar or a
# keyboard shortcut. The installer copies it into Word's STARTUP folder.
#
# Macro names are read from VbaCommands.cs, so the template always matches the
# add-in. Re-run this after adding or renaming a command:
#
#     powershell -ExecutionPolicy Bypass -File Ribbon\Build-MacrosTemplate.ps1
#
# Needs Word, and Windows' "language for non-Unicode programs" set to Hebrew (VBA
# stores the Hebrew macro names in that code page). Word's "Trust access to the VBA
# project object model" is switched on for the run and restored afterwards.

$ErrorActionPreference = 'Stop'
$root   = Split-Path $PSScriptRoot -Parent
$source = Join-Path $PSScriptRoot 'VbaCommands.cs'
$target = Join-Path $root 'Resources\KleiKodeshMacros.dotm'

# "public void Nakdan() => AddinCommands.Run(...)" and "public void <Hebrew>() => Nakdan();"
# The Hebrew alias calls its English twin, so each macro calls the English member.
$code = [IO.File]::ReadAllText($source, [Text.Encoding]::UTF8)
$macros = [regex]::Matches($code, 'public void (\w+)\(\) => (\w+)?') | ForEach-Object {
    $name = $_.Groups[1].Value
    $twin = $_.Groups[2].Value
    $member = if ($twin -and $twin -ne 'AddinCommands') { $twin } else { $name }
    "Public Sub $name()`r`n    KleiKodesh.$member`r`nEnd Sub"
}
if (-not $macros) { throw "No commands found in $source" }

$module = @"
' Klei Kodesh add-in commands. Each macro runs the ribbon command of the same name.
' Generated by Ribbon\Build-MacrosTemplate.ps1 - edit VbaCommands.cs, not this module.

Private Function KleiKodesh() As Object
    Set KleiKodesh = Application.COMAddIns("KleiKodesh").Object
End Function

$($macros -join "`r`n`r`n")
"@

$securityKey = 'HKCU:\Software\Microsoft\Office\16.0\Word\Security'
$previous = (Get-ItemProperty $securityKey -Name AccessVBOM -ErrorAction SilentlyContinue).AccessVBOM
New-Item $securityKey -Force -ErrorAction SilentlyContinue | Out-Null
Set-ItemProperty $securityKey -Name AccessVBOM -Value 1 -Type DWord

$word = New-Object -ComObject Word.Application
try {
    $doc = $word.Documents.Add()
    $component = $doc.VBProject.VBComponents.Add(1)   # standard module
    $component.Name = 'KleiKodesh'
    $component.CodeModule.AddFromString($module)
    if (Test-Path $target) { Remove-Item $target }
    $doc.SaveAs2([ref]$target, [ref]15)                # wdFormatXMLTemplateMacroEnabled
    $doc.Close([ref]0)
}
finally {
    $word.Quit()
    [Runtime.InteropServices.Marshal]::ReleaseComObject($word) | Out-Null
    if ($null -eq $previous) { Remove-ItemProperty $securityKey -Name AccessVBOM }
    else { Set-ItemProperty $securityKey -Name AccessVBOM -Value $previous -Type DWord }
}
"Wrote $target ($($macros.Count) macros)"
