"""Builds Resources\\KleiKodeshMacros.he.dotm and .en.dotm from VbaCommands.cs.

One macro per add-in command, so users can put any command on the Quick Access
Toolbar or a keyboard shortcut. The .he template names the macros by their Hebrew
ribbon labels, the .en one by the English ids. Neither is installed automatically:
the user picks one in the installer's settings page or the add-in's settings pane
(KleiKodesh.Helpers.VbaMacrosTemplate), which copies it into Word's STARTUP folder.

A .dotm is a zip; the macros live in word/vbaProject.bin, a compound file (MS-CFB)
holding MS-OVBA-compressed streams. This script reads vbaProject.bin from
Ribbon\\macros_template_base.dotm (not shipped), replaces the KleiKodesh module
source, drops the compiled p-code (Word recompiles from source on load) and writes
one zip per language. No Word, no VBA trust setting.

    python KleiKodeshVsto\\Ribbon\\build_macros_template.py

Re-run after adding or renaming a command in VbaCommands.cs.
"""
import io
import os
import re
import struct
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
SOURCE = os.path.join(HERE, 'VbaCommands.cs')
BASE = os.path.join(HERE, 'macros_template_base.dotm')
TARGET = os.path.join(HERE, '..', 'Resources', 'KleiKodeshMacros.%s.dotm')
MODULE = 'KleiKodesh'
CODEPAGE = 'cp1255'   # VBA stores source in the ANSI code page; Hebrew names need 1255
NOT_ACTIVE_HE = 'התוסף כלי קודש אינו פעיל'


def module_source(lang):
    code = io.open(SOURCE, encoding='utf-8-sig').read()
    lines = ['Attribute VB_Name = "%s"' % MODULE,
             "' Klei Kodesh add-in commands. Each macro runs the ribbon command of the same name.",
             "' Generated by Ribbon\\build_macros_template.py from VbaCommands.cs - do not edit.",
             '',
             '',
             "' The add-in's command object, or a message and a quiet stop when the add-in",
             "' is missing, disabled or not loaded - never a VBA error dialog.",
             'Private Function KleiKodeshAddin() As Object',
             '    Dim addin As Object',
             '    On Error Resume Next',
             '    Set addin = Application.COMAddIns("KleiKodesh")',
             '    If Not addin Is Nothing Then',
             '        If addin.Connect Then Set KleiKodeshAddin = addin.Object',
             '    End If',
             '    On Error GoTo 0',
             '    If KleiKodeshAddin Is Nothing Then',
             '        MsgBox "%s" & vbCrLf & "The Klei Kodesh add-in is not active.", vbExclamation' % NOT_ACTIVE_HE,
             '        End',
             '    End If',
             'End Function']
    # "public void Nakdan() => AddinCommands.Run(...)" / "public void <Hebrew>() => Nakdan();"
    # The Hebrew alias calls its English twin, so every macro calls an English member.
    # English ids are ASCII and the Hebrew labels are not: that picks each template's names.
    for name, twin in re.findall(r'public void (\w+)\(\) => (\w+)', code):
        if name.isascii() != (lang == 'en'):
            continue
        member = name if twin == 'AddinCommands' else twin
        lines += ['', 'Public Sub %s()' % name, '    KleiKodeshAddin.%s' % member, 'End Sub']
    if len(lines) < 10:
        raise SystemExit('No commands found in ' + SOURCE)
    return ('\r\n'.join(lines) + '\r\n').encode(CODEPAGE)


# ── MS-OVBA compression ──────────────────────────────────────────────────────

def decompress(data):
    assert data[0] == 1, 'not an MS-OVBA compressed container'
    out = bytearray()
    pos = 1
    while pos < len(data):
        header = struct.unpack_from('<H', data, pos)[0]
        size = (header & 0x0FFF) + 3
        chunk_end = pos + size
        pos += 2
        start = len(out)
        if not header & 0x8000:                         # raw chunk
            out += data[pos:pos + 4096]
            pos = chunk_end
            continue
        while pos < chunk_end:
            flags = data[pos]
            pos += 1
            for bit in range(8):
                if pos >= chunk_end:
                    break
                if not flags >> bit & 1:
                    out.append(data[pos])
                    pos += 1
                    continue
                token = struct.unpack_from('<H', data, pos)[0]
                pos += 2
                bits = max((len(out) - start - 1).bit_length(), 4)
                offset = (token >> (16 - bits)) + 1
                length = (token & (0xFFFF >> bits)) + 3
                for _ in range(length):
                    out.append(out[-offset])
    return bytes(out)


def compress(data):
    out = bytearray(b'\x01')
    for start in range(0, len(data), 4096):
        chunk = data[start:start + 4096]
        body = bytearray()
        pos = 0
        while pos < len(chunk):
            flag_at = len(body)
            body.append(0)
            for bit in range(8):
                if pos >= len(chunk):
                    break
                bits = max((pos - 1).bit_length(), 4)
                max_len = (0xFFFF >> bits) + 3
                best_len, best_off = 0, 0
                for cand in range(pos - 1, -1, -1):
                    n = 0
                    while n < max_len and pos + n < len(chunk) and chunk[cand + n] == chunk[pos + n]:
                        n += 1
                    if n > best_len:
                        best_len, best_off = n, pos - cand
                if best_len >= 3:
                    body += struct.pack('<H', ((best_off - 1) << (16 - bits)) | (best_len - 3))
                    body[flag_at] |= 1 << bit
                    pos += best_len
                else:
                    body.append(chunk[pos])
                    pos += 1
        if len(body) > 4096 and len(chunk) == 4096:     # incompressible: store raw
            out += struct.pack('<H', 0x3000 | (4096 + 2 - 3)) + chunk
        else:
            out += struct.pack('<H', 0xB000 | (len(body) + 2 - 3)) + body
    return bytes(out)


# ── MS-CFB (compound file) ───────────────────────────────────────────────────

FREE, END = 0xFFFFFFFF, 0xFFFFFFFE


def read_cfb(data):
    """Returns {path: bytes} for every stream, path like 'VBA/dir'."""
    sector = 1 << struct.unpack_from('<H', data, 30)[0]
    mini = 1 << struct.unpack_from('<H', data, 32)[0]
    first_dir, = struct.unpack_from('<I', data, 48)
    cutoff, first_minifat = struct.unpack_from('<II', data, 56)
    difat = [s for s in struct.unpack_from('<109I', data, 76) if s < 0xFFFFFFFA]
    sec = lambda n: data[(n + 1) * sector:(n + 2) * sector]
    fat = []
    for s in difat:
        fat += struct.unpack('<%dI' % (sector // 4), sec(s))

    def chain(first, table):
        n = first
        while n < 0xFFFFFFFA:
            yield n
            n = table[n]

    read = lambda first: b''.join(sec(n) for n in chain(first, fat))
    raw_dir = read(first_dir)
    entries = [raw_dir[i:i + 128] for i in range(0, len(raw_dir), 128)]
    minifat = list(struct.unpack('<%dI' % (len(read(first_minifat)) // 4), read(first_minifat))) \
        if first_minifat < 0xFFFFFFFA else []
    root_stream = read(struct.unpack_from('<I', entries[0], 116)[0])

    streams = {}

    def walk(index, prefix):
        if index >= 0xFFFFFFFA:
            return
        e = entries[index]
        name_len, = struct.unpack_from('<H', e, 64)
        name = e[:max(name_len - 2, 0)].decode('utf-16-le')
        kind = e[66]
        left, right, child = struct.unpack_from('<III', e, 68)
        start, size = struct.unpack_from('<II', e, 116)
        walk(left, prefix)
        walk(right, prefix)
        if kind == 1:
            walk(child, prefix + name + '/')
        elif kind == 2:
            if size < cutoff:
                body = b''.join(root_stream[n * mini:(n + 1) * mini] for n in chain(start, minifat))
            else:
                body = read(start)
            streams[prefix + name] = body[:size]

    walk(struct.unpack_from('<I', entries[0], 76)[0], '')
    return streams


def write_cfb(streams):
    """Writes {path: bytes} (one storage level deep) as a version-3 compound file."""
    SECTOR, MINI, CUTOFF = 512, 64, 4096

    # Directory tree: root -> top-level names; storages -> their children.
    tree = {'': []}
    for path in streams:
        parts = path.split('/')
        if len(parts) == 2 and parts[0] not in tree:
            tree[parts[0]] = []
            tree[''].append(parts[0])
        tree[parts[0] if len(parts) == 2 else ''].append(parts[-1])

    entries = [{'name': 'Root Entry', 'type': 5, 'path': None}]

    def add_children(storage):
        names = sorted(tree[storage], key=lambda n: (len(n), n.upper()))
        ids = []
        for n in names:
            path = (storage + '/' + n) if storage else n
            entries.append({'name': n, 'type': 1 if path in tree else 2, 'path': path})
            ids.append(len(entries) - 1)

        def balance(lo, hi):                            # sorted ids -> balanced BST root
            if lo > hi:
                return FREE
            mid = (lo + hi) // 2
            entries[ids[mid]]['left'] = balance(lo, mid - 1)
            entries[ids[mid]]['right'] = balance(mid + 1, hi)
            return ids[mid]

        root = balance(0, len(ids) - 1)
        for i in ids:
            if entries[i]['type'] == 1:
                entries[i]['child'] = add_children(entries[i]['path'])
        return root

    entries[0]['child'] = add_children('')

    sectors, fat = [], []

    def put(blob, table, size):
        first = len(table)
        count = max((len(blob) + size - 1) // size, 1) if blob else 0
        for i in range(count):
            table.append(first + i + 1 if i < count - 1 else END)
        return (first if count else END), count

    mini_stream, minifat = bytearray(), []
    big = []
    for e in entries:
        e.setdefault('left', FREE), e.setdefault('right', FREE), e.setdefault('child', FREE)
        e['start'], e['size'] = END, 0
        if e['type'] == 2:
            body = streams[e['path']]
            e['size'] = len(body)
            if len(body) < CUTOFF:
                e['start'], _ = put(body, minifat, MINI)
                mini_stream += body + b'\0' * (-len(body) % MINI)
            else:
                big.append((e, body))

    def alloc(blob):
        first, count = put(blob, fat, SECTOR)
        padded = blob + b'\0' * (-len(blob) % SECTOR)
        sectors.extend(padded[i:i + SECTOR] for i in range(0, len(padded), SECTOR))
        return first

    for e, body in big:
        e['start'] = alloc(body)
    entries[0]['start'] = alloc(bytes(mini_stream)) if mini_stream else END
    entries[0]['size'] = len(mini_stream)
    minifat_raw = struct.pack('<%dI' % len(minifat), *minifat)
    minifat_raw += b'\xff' * (-len(minifat_raw) % SECTOR)
    first_minifat = alloc(minifat_raw) if minifat else END

    raw_dir = bytearray()
    for e in entries:
        name = e['name'].encode('utf-16-le') + b'\0\0'
        raw_dir += name.ljust(64, b'\0') + struct.pack('<HBB', len(name), e['type'], 1)
        raw_dir += struct.pack('<III', e['left'], e['right'], e['child'])
        raw_dir += b'\0' * 36 + struct.pack('<III', e['start'], e['size'], 0)
    while len(raw_dir) % SECTOR:
        raw_dir += (b'\0' * 64 + struct.pack('<HBB', 0, 0, 0) + struct.pack('<III', FREE, FREE, FREE)
                    + b'\0' * 36 + struct.pack('<III', 0, 0, 0))
    first_dir = alloc(bytes(raw_dir))

    # FAT sectors describe themselves too (0xFFFFFFFD = FATSECT).
    fat_count = 1
    while (len(fat) + fat_count) > fat_count * (SECTOR // 4):
        fat_count += 1
    fat_start = len(fat)
    fat += [0xFFFFFFFD] * fat_count
    fat += [FREE] * (fat_count * (SECTOR // 4) - len(fat))
    fat_raw = struct.pack('<%dI' % len(fat), *fat)
    assert fat_count <= 109
    difat = [fat_start + i for i in range(fat_count)] + [FREE] * (109 - fat_count)

    header = struct.pack('<8s16sHHHHH6sIIIIIIIII', bytes.fromhex('D0CF11E0A1B11AE1'), b'\0' * 16,
                         0x3E, 3, 0xFFFE, 9, 6, b'\0' * 6, 0, fat_count, first_dir, 0, CUTOFF,
                         first_minifat, len(minifat_raw) // SECTOR if minifat else 0, END, 0)
    header += struct.pack('<109I', *difat)
    return header + b''.join(sectors) + fat_raw


# ── dir stream: point every module at offset 0 (no p-code before the source) ─

def zero_module_offsets(dir_data):
    out = bytearray(dir_data)
    pos = 0
    while pos < len(out):
        rec_id, size = struct.unpack_from('<HI', out, pos)
        if rec_id == 0x0009:                            # PROJECTVERSION: size says 4, body is 6
            size = 6
        if rec_id == 0x0031:                            # MODULEOFFSET
            struct.pack_into('<I', out, pos + 6, 0)
        pos += 6 + size
    return bytes(out)


def main():
    for lang in ('he', 'en'):
        build(lang)


def build(lang):
    target = TARGET % lang
    with zipfile.ZipFile(BASE) as z:
        parts = [(i, z.read(i.filename)) for i in z.infolist()]
    vba = read_cfb(dict(parts_by_name(parts))['word/vbaProject.bin'])

    dir_data = decompress(vba['VBA/dir'])
    new = {k: v for k, v in vba.items() if not k.startswith('VBA/__SRP_')}
    new['VBA/dir'] = compress(zero_module_offsets(dir_data))
    new['VBA/_VBA_PROJECT'] = b'\xCC\x61\xFF\xFF\x00\x00\x00'   # no p-code cache: recompile on load
    for name in [k for k in vba if k.startswith('VBA/') and k not in ('VBA/dir', 'VBA/_VBA_PROJECT')
                 and not k.startswith('VBA/__SRP_')]:
        source = module_source(lang) if name == 'VBA/' + MODULE else existing_source(vba, dir_data, name)
        new[name] = compress(source)

    bin_data = write_cfb(new)                           # build fully before touching the file
    with zipfile.ZipFile(target, 'w', zipfile.ZIP_DEFLATED) as z:
        for info, data in parts:
            z.writestr(info, bin_data if info.filename == 'word/vbaProject.bin' else data)
    print('Wrote %s' % os.path.normpath(target))


def parts_by_name(parts):
    return ((i.filename, d) for i, d in parts)


def existing_source(vba, dir_data, stream):
    """Source of a module we do not generate (ThisDocument), read past its p-code."""
    name = stream.split('/', 1)[1]
    pos, current = 0, None
    while pos < len(dir_data):
        rec_id, size = struct.unpack_from('<HI', dir_data, pos)
        if rec_id == 0x0009:
            size = 6
        body = dir_data[pos + 6:pos + 6 + size]
        if rec_id == 0x001A:                            # MODULESTREAMNAME
            current = body.decode(CODEPAGE)
        if rec_id == 0x0031 and current == name:
            return decompress(vba[stream][struct.unpack('<I', body)[0]:])
        pos += 6 + size
    raise SystemExit('Module %s not found in dir stream' % name)


if __name__ == '__main__':
    main()
