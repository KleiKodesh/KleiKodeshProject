# Regenerates ToratEmetNamesData.cs from a Torat Emet install (run: python -I generate-torat-emet-names.py <install folder>).
# Sources, both cp1255 text files of the install:
#   Config.txt      [TranslateDictionary]  ENGLISH_FOLDER_TOKEN=hebrew folder name  (the program's own translation of its folder names)
#   BooksConfig.txt [Books\<dir>\<file>_<hebrew title>]  sections: the title the program shows for each book file
# A book file with no section there falls back to its own first '$ ' title line.
# Output rows (tab separated):  F <token> <title>  and  B <path under Books, lower case, backslashes> <title> [<ForcedBookName>]
import os, re, sys
BS = chr(92)

root = sys.argv[1]
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'ToratEmetNamesData.cs')
read = lambda name: open(os.path.join(root, name), encoding='cp1255', errors='replace').read().splitlines()

folders = {}
lines = read('Config.txt')
start = [i for i, l in enumerate(lines) if l.strip() == '[TranslateDictionary]'][0]
for l in lines[start + 1:]:
    if l.startswith('['):
        break
    if '=' in l:
        k, v = l.split('=', 1)
        folders[k.strip()] = v.strip()

sections, current = {}, None
for l in read('BooksConfig.txt'):
    if l.startswith('[Books' + chr(92)) and l.rstrip().endswith(']'):
        current = l.strip()[1:-1]
        sections[current] = {}
    elif current and '=' in l:
        k, v = l.split('=', 1)
        sections[current][k] = v

files = [os.path.relpath(os.path.join(r, f), os.path.join(root, 'Books')) for r, _, fs in os.walk(os.path.join(root, 'Books')) for f in fs]
rows = []
for f in sorted(files, key=str.lower):
    prefix = ('Books' + chr(92) + f + '_').lower()
    hit = [k for k in sections if k.lower().startswith(prefix)]
    if not hit:
        # No section in BooksConfig.txt: the book's own first '$ ' title line (a book file, never a .dat or other dummy).
        if f.lower().endswith('.txt'):
            for line in open(os.path.join(root, 'Books', f), encoding='cp1255', errors='replace').read().splitlines()[:100]:
                if line.startswith('$ ') and line[2:].strip():
                    rows.append('B	' + f.lower() + '	' + line[2:].strip())
                    break
        continue
    title = hit[0][len(prefix):].strip()
    forced = sections[hit[0]].get('ForcedBookName', '').strip()
    if not title or title.lower() == os.path.basename(f).lower():
        continue
    rows.append('B\t' + f.lower() + '\t' + title + ('\t' + forced if forced and forced != title else ''))
rows = ['F\t' + k + '\t' + v for k, v in sorted(folders.items())] + rows
assert '"""' not in '\n'.join(rows)
with open(out, 'w', encoding='utf-8-sig', newline='\n') as w:
    w.write('// <auto-generated> by generate-torat-emet-names.py from a Torat Emet install (Config.txt TranslateDictionary + BooksConfig.txt). Do not edit by hand. </auto-generated>\n')
    w.write('namespace KitveiHakodesh.Core.LocalFiles.ToratEmet;\n\ninternal static class ToratEmetNamesData\n{\n    public const string Rows = """\n')
    w.write('\n'.join(rows) + '\n""";\n}\n')
print(len(folders), 'folder tokens,', len(rows) - len(folders), 'books')
