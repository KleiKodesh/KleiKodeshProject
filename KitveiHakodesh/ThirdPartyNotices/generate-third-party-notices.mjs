// Writes THIRD-PARTY-NOTICES.txt: every third-party component and data set the app ships, with
// its copyright line, license and the full license text where the license asks for it.
//
//   node generate-third-party-notices.mjs [outFile]
//   (default outFile: bin/THIRD-PARTY-NOTICES.txt beside this script)
//
// Run by the KitveiHakodeshService build (target GenerateThirdPartyNotices), so every build -
// dev and release - ships a fresh file. The service copies it into its output and publish
// folder (the app's KitveiHakodeshService\ folder); KitveiHakodeshLib also copies it to the
// app folder itself.
//
// Sources:
//   curated-notices.mjs   library data, ported code, fonts, files bundled by hand
//   npm                   production packages of vue-frontend and hebrew-typing-tutor
//                         (package-lock.json, read from the installed node_modules)
//   NuGet                 the service's project.assets.json (Core, FtsLib, FastDocView, ...)
//                         and every shipped packages.config (add-in, host, task panes)
//   Cargo                 the setup exe's crates (cargo metadata), when cargo is installed
// A source that is not installed yet is reported in the file, never silently dropped.

import fs from 'node:fs'
import path from 'node:path'
import zlib from 'node:zlib'
import crypto from 'node:crypto'
import { execFileSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
