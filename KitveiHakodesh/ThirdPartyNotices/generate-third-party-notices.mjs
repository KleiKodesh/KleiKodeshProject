const here = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(here, '..', '..') // KleiKodeshProject
const outFile = path.resolve(process.argv[2] || path.join(here, 'bin', 'THIRD-PARTY-NOTICES.txt'))
const warnings = []

// ---- License texts, printed once each ---------------------------------------------------

const texts = [] // { id, title, body }
const textByHash = new Map()

function addText(title, body) {
  body = body.replace(/^﻿/, '').replace(/\r\n?/g, '\n').replace(/[ \t]+$/gm, '').trim()
  if (!body) return null
  const hash = crypto.createHash('sha1').update(body.replace(/\s+/g, ' ')).digest('hex')
  if (textByHash.has(hash)) return textByHash.get(hash)
  const id = `T${texts.length + 1}`
  texts.push({ id, title, body })
  textByHash.set(hash, id)
  return id
}

const LICENSE_FILE = /^(licen[cs]e|copying|notice|unlicense)([-._].*)?$/i

function licenseFilesIn(dir) {
  try {
    return fs.readdirSync(dir, { withFileTypes: true })
      .filter((e) => e.isFile() && LICENSE_FILE.test(e.name))
      .map((e) => path.join(dir, e.name))
      .sort()
  } catch { return [] }
}

function readText(file) {
  try { return fs.readFileSync(file, 'utf8') } catch { return '' }
}

