/** Text ids for a component: its own license files, or a standard text when it ships none. */
function textsFor(name, files, spdx, copyright) {
  const ids = files.map((f) => addText(`${name}: ${path.basename(f)}`, readText(f))).filter(Boolean)
  if (ids.length) return ids
  const s = (spdx || '').toUpperCase()
  if (/APACHE-2\.0/.test(s)) return [addText('Apache License 2.0', readText(APACHE_FILE))]
  if (/^\(?MIT\b/.test(s)) return [addText(`${name}: MIT`, MIT(copyright || `Copyright (c) the ${name} authors`))]
  // Slint is offered under GPL-3.0-only or its own licenses; the setup program uses GPL-3.0.
  if (/^\(?GPL-3\.0/.test(s)) return [addText('GNU General Public License v3', readText(GPL3_FILE))]
  if (/^\(?BSL-1\.0/.test(s)) return [addText('Boost Software License 1.0', BSL)]
  // Only an SPDX id is a license we could have printed; a plain description needs no text.
  if (s && !/\s/.test(s.replace(/[ ()]+(OR|AND|WITH)[ ()]+/g, '-'))) warnings.push(`${name}: ships no license file (${spdx}); see its project page`)
  return []
}

// ---- Curated ----------------------------------------------------------------------------

function curatedSection(group) {
  return group.entries.map((e) => ({
    name: e.name,
    use: e.use,
    copyright: e.copyright,
    license: e.license + (e.licenseUrl ? ` (${e.licenseUrl})` : ''),
    url: e.url,
    notice: e.notice,
    source: e.source,
    texts: (e.files || []).map((f) => {
      const full = path.join(root, f)
      if (!fs.existsSync(full)) { warnings.push(`${e.name}: missing ${f}`); return null }
      return addText(`${e.name}: ${path.basename(f)}`, readText(full))
    }).filter(Boolean),
  }))
}

// ---- npm --------------------------------------------------------------------------------

function npmPackages(appDir) {
  const lockFile = path.join(root, appDir, 'package-lock.json')
  if (!fs.existsSync(lockFile)) { warnings.push(`${appDir}: no package-lock.json`); return [] }
  const lock = JSON.parse(readText(lockFile))
  const out = []
  for (const [key, meta] of Object.entries(lock.packages || {})) {
    if (!key || meta.dev || meta.link) continue
    const dir = path.join(root, appDir, key)
    const pkgFile = path.join(dir, 'package.json')
    if (!fs.existsSync(pkgFile)) {
      if (!meta.optional) warnings.push(`${appDir}: ${key} is not installed (run npm install)`)
      continue
    }
    const pkg = JSON.parse(readText(pkgFile))
    const author = typeof pkg.author === 'string' ? pkg.author : pkg.author?.name
    const repo = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url
    const license = pkg.license || (Array.isArray(pkg.licenses) ? pkg.licenses.map((l) => l.type || l).join(' OR ') : '') || meta.license || 'UNKNOWN'
    out.push({
      key: `${pkg.name}@${pkg.version}`,
      name: `${pkg.name} ${pkg.version}`,
      copyright: author ? `Copyright (c) ${author}` : '',
      license,
      url: pkg.homepage || (repo || '').replace(/^git\+/, '').replace(/\.git$/, ''),
      dir,
    })
  }
  return out
}

// ---- NuGet ------------------------------------------------------------------------------

/** Minimal zip reader (central directory + deflate), enough for a .nupkg. */
function readZip(file) {
  const buf = fs.readFileSync(file)
  let eocd = buf.length - 22
  while (eocd >= 0 && buf.readUInt32LE(eocd) !== 0x06054b50) eocd--
  if (eocd < 0) return new Map()
  const count = buf.readUInt16LE(eocd + 10)
  let p = buf.readUInt32LE(eocd + 16)
  const entries = new Map()
  for (let i = 0; i < count; i++) {
    const method = buf.readUInt16LE(p + 10)
    const csize = buf.readUInt32LE(p + 20)
    const nameLen = buf.readUInt16LE(p + 28), extraLen = buf.readUInt16LE(p + 30), commentLen = buf.readUInt16LE(p + 32)
    const local = buf.readUInt32LE(p + 42)
    const name = buf.toString('utf8', p + 46, p + 46 + nameLen)
    entries.set(name, () => {
      const start = local + 30 + buf.readUInt16LE(local + 26) + buf.readUInt16LE(local + 28)
      const data = buf.subarray(start, start + csize)
      return (method === 8 ? zlib.inflateRawSync(data) : data).toString('utf8')
    })
    p += 46 + nameLen + extraLen + commentLen
  }
  return entries
}

function xmlTag(xml, tag) {
  const m = xml.match(new RegExp(`<${tag}(\\s[^>]*)?>([\\s\\S]*?)</${tag}>`, 'i'))
  return m ? { attrs: m[1] || '', value: m[2].trim().replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&apos;/g, "'") } : null
}

const globalNuGet = process.env.NUGET_PACKAGES || path.join(process.env.USERPROFILE || process.env.HOME || '', '.nuget', 'packages')

/** A NuGet package's notice, from its extracted folder (or global cache) and its .nupkg. */
function nugetPackage(id, version, folders) {
  const candidates = [
    ...folders.map((f) => path.join(f, id.toLowerCase(), version.toLowerCase())),
    ...folders.map((f) => path.join(f, `${id}.${version}`)),
    path.join(globalNuGet, id.toLowerCase(), version.toLowerCase()),
  ]
  const dir = candidates.find((d) => fs.existsSync(d))
  if (!dir) { warnings.push(`NuGet ${id} ${version}: package folder not found (restore first)`); return null }
  let nuspec = ''
  const files = []
  const nuspecFile = fs.readdirSync(dir).find((n) => n.toLowerCase().endsWith('.nuspec'))
  if (nuspecFile) nuspec = readText(path.join(dir, nuspecFile))
  const nupkg = fs.readdirSync(dir).find((n) => n.toLowerCase().endsWith('.nupkg'))
  let zipLicense = []
  if (nupkg) {
    try {
      const zip = readZip(path.join(dir, nupkg))
      for (const [name, read] of zip) {
        if (!nuspec && !name.includes('/') && name.toLowerCase().endsWith('.nuspec')) nuspec = read()
        if (!name.includes('/') && LICENSE_FILE.test(name)) zipLicense.push({ name, read })
      }
    } catch (e) { warnings.push(`NuGet ${id} ${version}: cannot read ${nupkg}: ${e.message}`) }
  }
  const lic = xmlTag(nuspec, 'license')
  let license = lic?.value || ''
  if (lic && /type="file"/i.test(lic.attrs)) {
    const f = path.join(dir, lic.value)
    if (fs.existsSync(f)) files.push(f)
    else { const z = zipLicense.find((e) => e.name.toLowerCase() === lic.value.toLowerCase()); if (z) zipLicense = [z] }
    license = 'see license text'
  }
  if (!license) license = xmlTag(nuspec, 'licenseUrl')?.value || ''
  // Microsoft's Office interop package carries no license metadata at all.
  if (!license && /^Microsoft\.Office\.Interop\./i.test(id)) license = 'Microsoft Office primary interop assembly (Microsoft license terms)'
  if (!license) license = 'UNKNOWN'
  files.push(...licenseFilesIn(dir))
  const copyright = xmlTag(nuspec, 'copyright')?.value || (xmlTag(nuspec, 'authors') ? `Authors: ${xmlTag(nuspec, 'authors').value}` : '')
  const name = `${id} ${version}`
  const ids = files.map((f) => addText(`${name}: ${path.basename(f)}`, readText(f))).filter(Boolean)
  if (!files.length) for (const z of zipLicense) { const t = addText(`${name}: ${z.name}`, z.read()); if (t) ids.push(t) }
  return {
    key: `${id.toLowerCase()}@${version.toLowerCase()}`,
    name,
    copyright,
    license,
    url: xmlTag(nuspec, 'projectUrl')?.value || `https://www.nuget.org/packages/${id}/${version}`,
    texts: ids.length ? ids : textsFor(name, [], license, copyright),
  }
}

function nugetPackages() {
  const out = new Map()
  const add = (p) => { if (p && !out.has(p.key)) out.set(p.key, p) }

  const assetsFile = path.join(root, 'KitveiHakodesh/CSharpBackend/KitveiHakodeshService/obj/project.assets.json')
  if (fs.existsSync(assetsFile)) {
    const assets = JSON.parse(readText(assetsFile))
    const folders = Object.keys(assets.packageFolders || {})
    for (const [key, lib] of Object.entries(assets.libraries || {})) {
      if (lib.type !== 'package') continue
      const [id, version] = key.split('/')
      add(nugetPackage(id, version, folders))
    }
  } else warnings.push('KitveiHakodeshService: obj/project.assets.json missing (restore first); its NuGet packages are not listed')

  let configs = []
  try {
    configs = execFileSync('git', ['ls-files', '*packages.config'], { cwd: root, encoding: 'utf8' }).split('\n').filter(Boolean)
  } catch { warnings.push('git not available: packages.config files not listed') }
  for (const rel of configs) {
    if (/test|debugger|bench|spike|demo/i.test(rel)) continue
    const dir = path.dirname(path.join(root, rel))
    const xml = readText(path.join(root, rel))
    for (const m of xml.matchAll(/<package\s+id="([^"]+)"\s+version="([^"]+)"/g)) {
      add(nugetPackage(m[1], m[2], [path.join(dir, '..', 'packages'), path.join(root, 'packages')]))
    }
  }
  return [...out.values()].sort((a, b) => a.name.localeCompare(b.name))
}

// ---- Cargo (the setup exe) ----------------------------------------------------------------

function cargoPackages() {
  const manifest = path.join(root, 'Build/installer-rs/Cargo.toml')
  if (!fs.existsSync(manifest)) return []
  let meta
  try {
    meta = JSON.parse(execFileSync('cargo', ['metadata', '--format-version', '1', '--locked', '--filter-platform', 'x86_64-pc-windows-msvc', '--manifest-path', manifest],
      { encoding: 'utf8', maxBuffer: 256 * 1024 * 1024, stdio: ['ignore', 'pipe', 'ignore'] }))
  } catch (e) {
    warnings.push('Setup program: cargo metadata failed; its crates are not listed')
    return []
  }
  const byId = new Map(meta.packages.map((p) => [p.id, p]))
  const nodes = new Map(meta.resolve.nodes.map((n) => [n.id, n]))
  // Only what is linked into the exe: normal dependencies, not build scripts or tests.
  const seen = new Set()
  const stack = [...meta.workspace_members]
  while (stack.length) {
    const id = stack.pop()
    if (seen.has(id)) continue
    seen.add(id)
    for (const d of nodes.get(id)?.deps || []) if (d.dep_kinds.some((k) => k.kind === null)) stack.push(d.pkg)
  }
  const out = []
  for (const id of seen) {
    if (meta.workspace_members.includes(id)) continue
    const p = byId.get(id)
    const dir = path.dirname(p.manifest_path)
    const name = `${p.name} ${p.version}`
    const files = licenseFilesIn(dir)
    if (p.license_file) files.push(path.join(dir, p.license_file))
    out.push({
      key: `${p.name}@${p.version}`,
      name,
      copyright: p.authors?.length ? `Copyright (c) ${p.authors.join(', ')}` : '',
      license: p.license || 'see license text',
      url: p.repository || p.homepage || `https://crates.io/crates/${p.name}`,
      texts: textsFor(name, [...new Set(files)], p.license, p.authors?.length ? `Copyright (c) ${p.authors.join(', ')}` : ''),
    })
  }
  return out.sort((a, b) => a.name.localeCompare(b.name))
}

// ---- Output -----------------------------------------------------------------------------

function entryLines(e) {
  const lines = [`* ${e.name}`]
  if (e.use) lines.push(`  Used for:  ${e.use}`)
  if (e.copyright) lines.push(`  Copyright: ${e.copyright}`)
  lines.push(`  License:   ${e.license}`)
  if (e.url) lines.push(`  Website:   ${e.url}`)
  if (e.notice) lines.push(`  Notice:    ${e.notice}`)
  if (e.source) lines.push(`  Source:    ${e.source}`)
  if (e.texts?.length) lines.push(`  Full text: ${e.texts.join(', ')} (under LICENSE TEXTS below)`)
  return lines.join('\n')
}

const sections = curatedGroups.map((g) => ({ title: g.title, entries: curatedSection(g) }))

const npmSeen = new Set()
const npm = []
for (const app of ['KitveiHakodesh/vue-frontend', 'hebrew-typing-tutor']) {
  for (const p of npmPackages(app)) {
    if (npmSeen.has(p.key)) continue
    npmSeen.add(p.key)
    npm.push({ ...p, texts: textsFor(p.name, licenseFilesIn(p.dir), p.license, p.copyright) })
  }
}
npm.sort((a, b) => a.name.localeCompare(b.name))
sections.push({ title: 'npm packages (the app interface)', entries: npm })
sections.push({ title: 'NuGet packages (the service, the app window and the Word add-in)', entries: nugetPackages() })
const cargo = cargoPackages()
if (cargo.length) sections.push({ title: 'Rust crates (the setup program)', entries: cargo })

const rule = '='.repeat(78)
let doc = `THIRD-PARTY NOTICES - Kitvei Hakodesh / Klei Kodesh

${ZAYIT_ATTRIBUTION}

This product includes the open-source components and open data listed below. Each is
used under its own license. Where a license asks for its full text to come with the
product, that text is under LICENSE TEXTS at the end (each text is printed once and
referred to by its number, e.g. T3).

The source code of Kitvei Hakodesh / Klei Kodesh: https://github.com/KleiKodesh/KleiKodeshProject
`
for (const s of sections) {
  doc += `\n${rule}\n${s.title.toUpperCase()} (${s.entries.length})\n${rule}\n\n`
  doc += s.entries.map(entryLines).join('\n\n') + '\n'
}
if (warnings.length) {
  doc += `\n${rule}\nNOT FULLY LISTED AT BUILD TIME\n${rule}\n\n` + warnings.map((w) => `- ${w}`).join('\n') + '\n'
}
doc += `\n${rule}\nLICENSE TEXTS\n${rule}\n`
for (const t of texts) doc += `\n----- ${t.id}: ${t.title} -----\n\n${t.body}\n`

fs.mkdirSync(path.dirname(outFile), { recursive: true })
const old = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf8') : null
const bom = '﻿' // Notepad opens it as UTF-8 for sure
if (old !== bom + doc.replace(/\n/g, '\r\n')) fs.writeFileSync(outFile, bom + doc.replace(/\n/g, '\r\n'), 'utf8')
const count = sections.reduce((n, s) => n + s.entries.length, 0)
console.log(`THIRD-PARTY-NOTICES.txt: ${count} components, ${texts.length} license texts, ${warnings.length} warnings -> ${outFile}`)
for (const w of warnings) console.log(`  warning: ${w}`)
